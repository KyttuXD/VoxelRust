HEADER = '''# VoxelRust base content.  (Generated by tools/gen_base.py; hand edits are fine too.)
#
# Everything in the game world is declared here: textures, blocks and items.
# This file is built into the game; a pack file (see docs/DATA.md) is read
# after it and may add to it or redefine anything by reusing its id.
#
#   texture <id> builtin <painter>            a built-in procedural texture
#   texture <id> paint <style> <r> <g> <b>    a built-in pattern in any colour
#   texture <id> flat <r> <g> <b> [noise n]   a plain colour with some grain
#   texture <id> file <image.tga>             a 16x16 TGA next to the pack file
#
#   block <id>
#     name <display name>
#     shape cube | cutout | translucent | cross | liquid | slab | stairs | fence | wall
#     box x0 y0 z0 x1 y1 z1                   custom shape, in 1/16ths of a block
#     tex <all>   or   tex <top> <side> <bottom>
#     light <0..15>      skyloss <0..15>      solid yes|no
#     hardness <seconds> drops <item>|nothing category <tab name>
#     rotate             four facings, placed facing the player
#     flip               also upside-down, placed by where you aim
#     unbreakable        hidden (no item)
#
#   item <id>
#     name <display name>     icon <texture>      category <tab name>
#     place <block>           brush <radius>      reach <blocks>     stack <n>
'''
w(HEADER)

def tex(id, src):
    w(f"texture {id} {src}")

PICK = {"stone", "cobble", "brick", "coal_ore", "iron_ore", "copper_ore", "crystal_ore", "ruby_ore", "sandstone",
        "stone_bricks", "ice", "marble", "slate", "granite", "basalt", "marble_tiles", "slate_bricks", "lamp"}
AXE = {"log", "planks", "pine_log", "planks_post", "planks_table", "crafting_table"}
SHOVEL = {"dirt", "grass", "sand", "gravel", "snow", "snowy_grass", "clay", "snow_layer"}


def tool_for(id, tex):
    base = id.replace("_stairs", "").replace("_slab", "").replace("_wall", "").replace("_fence", "")
    if base in PICK or "concrete" in id or "terracotta" in id:
        return "pick"
    if base in AXE or base.endswith("_log") or base.endswith("_planks") or base.endswith("_chest"):
        return "axe"
    if base in SHOVEL:
        return "shovel"
    return None


def block(id, name, tex, shape=None, cat=None, **kw):
    t = tool_for(id, tex)
    if t and "tool" not in kw:
        kw["tool"] = t
    w(f"block {id}")
    w(f"  name {name}")
    if shape:
        w(f"  shape {shape}")
    w(f"  tex {tex}")
    if cat:
        w(f"  category {cat}")
    for k, v in kw.items():
        if v is True:
            w(f"  {k}")
        elif isinstance(v, list):
            for line in v:
                w(f"  {k} {line}")
        else:
            w(f"  {k} {v}")

