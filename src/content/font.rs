pub const TEX_W: usize = 128;
pub const TEX_H: usize = 64;
/// Glyphs sit in 8x8 cells, 16 per row.
pub const CELL: usize = 8;
/// Horizontal advance in font pixels.
pub const ADVANCE: f32 = 6.0;

/// Which glyph draws character `c`.
pub fn glyph_index(c: char) -> usize {
    let c = c.to_ascii_uppercase();
    match c {
        ' '..='`' => c as usize - 32,
        '{' => 8,
        '}' => 9,
        '|' => 1,
        '~' => 13,
        _ => 31, // '?'
    }
}

/// The font as a 128 x 64 RGBA texture: white glyphs on transparent.
pub fn build_texture() -> Vec<u8> {
    let mut t = alloc::vec![0u8; TEX_W * TEX_H * 4];
    for (g, rows) in GLYPHS.iter().enumerate() {
        let (cx, cy) = (g % 16 * CELL, g / 16 * CELL);
        for (y, row) in rows.iter().enumerate() {
            for x in 0..5 {
                if row & (0x10 >> x) != 0 {
                    let o = ((cy + y) * TEX_W + cx + 1 + x) * 4;
                    t[o..o + 4].copy_from_slice(&[255, 255, 255, 255]);
                }
            }
        }
    }
    t
}
