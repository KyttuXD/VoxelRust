/// Where the lower-case glyphs start in the texture (after the 65 upper-case ones).
const LOWER_AT: usize = 65;

pub const TEX_W: usize = 128;
pub const TEX_H: usize = 64;
/// Glyphs sit in 8x8 cells, 16 per row.
pub const CELL: usize = 8;
/// Horizontal advance in font pixels.
pub const ADVANCE: f32 = 6.0;

/// Which glyph draws character `c`.
pub fn glyph_index(c: char) -> usize {
    let c = c.to_ascii_uppercase();
    match c {
        ' '..='`' => c as usize - 32,
        '{' => 8,
        '}' => 9,
        '|' => 1,
        '~' => 13,
        _ => 31, // '?'
    }
}

/// As [`glyph_index`], but a lower-case letter keeps its own glyph.
pub fn glyph_index_cased(c: char) -> usize {
    if c.is_ascii_lowercase() {
        LOWER_AT + (c as usize - 'a' as usize)
    } else {
        glyph_index(c)
    }
}

/// The font as a 128 x 64 RGBA texture: white glyphs on transparent.
pub fn build_texture() -> Vec<u8> {
    let mut t = alloc::vec![0u8; TEX_W * TEX_H * 4];
    for (g, rows) in GLYPHS.iter().enumerate() {
        let (cx, cy) = (g % 16 * CELL, g / 16 * CELL);
        for (y, row) in rows.iter().enumerate() {
            for x in 0..5 {
                if row & (0x10 >> x) != 0 {
                    let o = ((cy + y) * TEX_W + cx + 1 + x) * 4;
                    t[o..o + 4].copy_from_slice(&[255, 255, 255, 255]);
                }
            }
        }
    }
    for (i, rows) in LOWER.iter().enumerate() {
        let g = LOWER_AT + i;
        let (cx, cy) = (g % 16 * CELL, g / 16 * CELL);
        for (y, row) in rows.iter().enumerate() {
            for x in 0..5 {
                if row & (0x10 >> x) != 0 {
                    let o = ((cy + y) * TEX_W + cx + 1 + x) * 4;
                    t[o..o + 4].copy_from_slice(&[255, 255, 255, 255]);
                }
            }
        }
    }
    t
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn lower_case_has_its_own_glyphs_only_when_asked() {
        assert_eq!(glyph_index('a'), glyph_index('A'));
        assert_ne!(glyph_index_cased('a'), glyph_index_cased('A'));
        assert_eq!(glyph_index_cased('A'), glyph_index('A'));
        assert_eq!(glyph_index_cased('z'), LOWER_AT + 25);
        let t = build_texture();
        // Every lower-case glyph has something drawn in its cell, and the cells fit the texture.
        for c in 'a'..='z' {
            let g = glyph_index_cased(c);
            let (cx, cy) = (g % 16 * CELL, g / 16 * CELL);
            assert!(cy + CELL <= TEX_H);
            let any = (0..CELL).any(|y| (0..CELL).any(|x| t[((cy + y) * TEX_W + cx + x) * 4 + 3] != 0));
            assert!(any, "no pixels for {c}");
        }
    }
}
