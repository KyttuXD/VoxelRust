//! The world's side of land from the server (a child module of `world.rs`, so
//! that it reaches the chunk table): in a world whose terrain this game cannot
//! make, the places where the world would generate a chunk ask the
//! [`Streamer`] instead, and chunks that arrive are shown like generated ones.
//! There is no distant terrain in such a world (it is made from the terrain
//! function, which this game does not have): see docs/MULTIPLAYER.md.

use super::*;
use alloc::string::String;
use crate::net::chunks::client_state::{Mode, Streamer};
use crate::net::chunks::codec;

impl World {
    /// From now on the land of this world comes from the server (`kind` is the
    /// world's kind as the server wrote it).
    pub fn start_streaming(&mut self, kind: &str) {
        self.remote = Some(Streamer::new(kind));
    }

    /// Whether the land is being fetched from the server (or the server's word on it is awaited).
    pub fn streaming(&self) -> bool {
        self.remote.as_ref().map_or(false, |r| r.takes_chunks())
    }

    /// Whether the server turned out to send no land: call [`World::stop_streaming`].
    pub fn stream_failed(&self) -> bool {
        self.remote.as_ref().map_or(false, |r| r.mode == Mode::Fallback)
    }

    /// The server said what it does about land.
    pub fn stream_caps(&mut self, flags: u8, limit: u32) {
        if let Some(r) = self.remote.as_mut() {
            r.on_caps(flags, limit);
        }
    }

    /// Give up on the server's land: chunks not here yet are generated by this
    /// game (ordinary terrain), and distant terrain comes back. Returns the name
    /// of the kind of world, for a message.
    pub fn stop_streaming(&mut self) -> String {
        let name = self.remote.take().map(|r| r.name).unwrap_or_default();
        for c in self.chunks.values_mut() {
            if c.data.is_none() {
                c.gen_requested = false;
            }
        }
        self.settled = false;
        name
    }

    /// Which chunks to ask the server for now (nearest the player first); call once a frame.
    pub fn stream_requests(&mut self, dt: f32) -> Vec<(i32, i32)> {
        let center = (self.last_center.0, self.last_center.1);
        match self.remote.as_mut() {
            // (Before the first `update` there is no centre to measure from.)
            Some(r) if center.0 != i32::MIN => r.plan(dt, center),
            Some(r) => r.plan(dt, (0, 0)),
            None => Vec::new(),
        }
    }

    /// A piece of a chunk arrived; when it completes one, the chunk is shown.
    pub fn stream_part(&mut self, cx: i32, cz: i32, part: u8, parts: u8, data: Vec<u8>) {
        let Some(r) = self.remote.as_mut() else { return };
        let Some(whole) = r.on_part(cx, cz, part, parts, data) else { return };
        self.stream_show((cx, cz), whole);
    }

    /// Show a chunk from its compressed bytes (from the server, or kept from before).
    fn stream_show(&mut self, key: (i32, i32), whole: Vec<u8>) {
        match codec::unpack(&whole) {
            Some(data) => {
                if let Some(r) = self.remote.as_mut() {
                    r.remember(key, whole);
                }
                self.deliver_chunk(key.0, key.1, data);
            }
            None => {
                if let Some(r) = self.remote.as_mut() {
                    r.damaged(key);
                }
            }
        }
    }

    /// A chunk made elsewhere (by the server) is here: the changes others made to
    /// it are put on, as for a generated chunk. Ignored if the world no longer wants it.
    pub fn deliver_chunk(&mut self, cx: i32, cz: i32, mut data: ChunkData) {
        if let Some(edits) = self.overlay.get(&(cx, cz)) {
            for &(x, y, z, b) in edits {
                data.set(x, y, z, b);
            }
        }
        if let Some(c) = self.chunks.get_mut(&(cx, cz)) {
            if c.data.is_none() {
                c.data = Some(Arc::new(data));
                c.dirty = true;
                self.log.note_generated(cx, cz);
            }
        }
        self.settled = false;
    }

    /// The first solid block from the top of the column at (x, z), as the height of the
    /// block above it (where to stand); `None` if that chunk is not here or the column is empty.
    pub fn standing_height(&self, x: i32, z: i32) -> Option<i32> {
        if !self.is_loaded(x, z) {
            return None;
        }
        (0..CH).rev().find(|&y| crate::block::is_solid(self.get(x, y, z))).map(|y| y + 1)
    }
}

/// Chunks the world was missing that the streamer had kept: shown at once.
pub(super) fn show_kept(w: &mut World, kept: Vec<((i32, i32), Vec<u8>)>) {
    for (key, whole) in kept {
        w.stream_show(key, whole);
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::net::chunks::gen::{make, tests::land};

    #[derive(Default)]
    struct CountSink {
        live: i32,
    }
    impl MeshSink for CountSink {
        fn upload(&mut self, m: &MeshData) -> GpuMesh {
            self.live += 1;
            GpuMesh { opaque_count: m.opaque.len() as i32, ..Default::default() }
        }
        fn free(&mut self, _: GpuMesh) {
            self.live -= 1;
        }
    }

    /// Run the world around chunk (cx, cz) until it has all it wants, with a server that
    /// answers every request at once from `land`. Returns the chunks asked for.
    fn settle_with_server(w: &mut World, cx: i32, cz: i32, r: i32, pool: &mut Pool, sink: &mut CountSink) -> Vec<(i32, i32)> {
        let mut asked = Vec::new();
        for _ in 0..4000 {
            w.update(cx, cz, r, pool, sink, &mut NullStore);
            for (x, z) in w.stream_requests(0.016) {
                asked.push((x, z));
                let pieces = make(land, w.seed, x, z, &[]).unwrap();
                let n = pieces.len() as u8;
                for (k, p) in pieces.iter().enumerate() {
                    w.stream_part(x, z, k as u8, n, p.clone());
                }
            }
            if w.settled {
                return asked;
            }
        }
        panic!("world never settled");
    }

    #[test]
    fn a_world_with_land_from_the_server_shows_the_servers_chunks_and_nothing_else() {
        let mut w = World::new(11);
        let mut pool = Pool::new(0, 11);
        let mut sink = CountSink::default();
        w.start_streaming("somewhere 46.8 -121.7 30 75");
        w.far_radius = 16;
        // Until the server says it sends land, nothing is asked for and nothing is made.
        for _ in 0..20 {
            w.update(0, 0, 2, &mut pool, &mut sink, &mut NullStore);
            assert!(w.stream_requests(0.016).is_empty());
        }
        assert!(w.chunks.values().all(|c| c.data.is_none()));
        w.stream_caps(crate::proto::CHUNKS_SERVED, 30_000);
        let asked = settle_with_server(&mut w, 0, 0, 2, &mut pool, &mut sink);
        let meshed = w.chunks.values().filter(|c| c.mesh.is_some()).count();
        assert_eq!(meshed, 21, "the same circle as for generated land");
        // Every chunk is the server's land, with nothing of the ordinary terrain.
        for (&(cx, cz), c) in w.chunks.iter() {
            if let Some(d) = &c.data {
                assert_eq!(**d, land(11, cx, cz), "chunk {cx} {cz}");
            }
        }
        assert!(asked.contains(&(0, 0)) && asked.len() >= 21);
        assert!(asked.iter().all(|k| k.0.abs() <= 3 && k.1.abs() <= 3), "only near the player");
        // No distant terrain: it would be made from a terrain function this game does not have.
        assert!(w.far.is_empty());
    }

    #[test]
    fn edits_told_before_a_chunk_arrives_are_on_it_when_it_does() {
        let mut w = World::new(11);
        let mut pool = Pool::new(0, 11);
        let mut sink = CountSink::default();
        w.start_streaming("somewhere");
        w.stream_caps(crate::proto::CHUNKS_SERVED, 30_000);
        // An edit by another player, told before its chunk is here.
        w.apply_remote(5, 50, 6, 9);
        settle_with_server(&mut w, 0, 0, 1, &mut pool, &mut sink);
        assert_eq!(w.get(5, 50, 6), 9);
        assert_eq!(w.get(5, 29, 6), 1, "the land under it is the server's");
    }

    #[test]
    fn chunks_walked_away_from_come_back_from_the_cache_without_asking_again() {
        let mut w = World::new(11);
        let mut pool = Pool::new(0, 11);
        let mut sink = CountSink::default();
        w.start_streaming("somewhere");
        w.stream_caps(crate::proto::CHUNKS_SERVED, 30_000);
        let first = settle_with_server(&mut w, 0, 0, 2, &mut pool, &mut sink);
        settle_with_server(&mut w, 40, 0, 2, &mut pool, &mut sink);
        assert!(!w.is_loaded(8, 8));
        let back = settle_with_server(&mut w, 0, 0, 2, &mut pool, &mut sink);
        assert!(!first.is_empty());
        assert!(back.is_empty(), "everything was kept: {back:?}");
        assert!(w.is_loaded(8, 8));
        assert_eq!(*w.chunks[&(0, 0)].data.clone().unwrap(), land(11, 0, 0));
    }

    #[test]
    fn a_server_that_sends_no_land_leaves_the_world_to_generate_its_own() {
        let mut w = World::new(11);
        let mut pool = Pool::new(0, 11);
        let mut sink = CountSink::default();
        w.start_streaming("somewhere");
        for _ in 0..5 {
            w.update(0, 0, 1, &mut pool, &mut sink, &mut NullStore);
        }
        assert!(w.chunks.values().all(|c| c.data.is_none()));
        w.stream_caps(0, 0);
        assert!(w.stream_failed() && !w.streaming());
        assert_eq!(w.stop_streaming(), "somewhere");
        for _ in 0..2000 {
            w.update(0, 0, 1, &mut pool, &mut sink, &mut NullStore);
            if w.settled {
                break;
            }
        }
        assert!(w.settled);
        assert_eq!(**w.chunks[&(0, 0)].data.as_ref().unwrap(), crate::worldgen::generate(11, 0, 0));
    }

    #[test]
    fn damaged_chunks_and_strangers_are_not_shown() {
        let mut w = World::new(11);
        w.start_streaming("somewhere");
        w.stream_caps(crate::proto::CHUNKS_SERVED, 30_000);
        w.chunks.insert((0, 0), Default::default());
        w.chunks.get_mut(&(0, 0)).unwrap().gen_requested = true;
        if let Some(r) = w.remote.as_mut() {
            r.want((0, 0));
        }
        assert_eq!(w.stream_requests(0.1), alloc::vec![(0, 0)]);
        // A piece for a chunk nobody asked for.
        w.stream_part(7, 7, 0, 1, alloc::vec![1, 2, 3]);
        // A piece that is not a chunk.
        w.stream_part(0, 0, 0, 1, alloc::vec![1, 2, 3, 4, 5, 6, 7, 8]);
        assert!(w.chunks[&(0, 0)].data.is_none());
        // It is asked for again after the retry time.
        assert!(w.stream_requests(0.9).is_empty());
        for _ in 0..2 {
            assert!(w.stream_requests(0.9).is_empty());
        }
        assert_eq!(w.stream_requests(0.5), alloc::vec![(0, 0)]);
        // A good one then arrives.
        let pieces = make(land, 11, 0, 0, &[]).unwrap();
        w.stream_part(0, 0, 0, pieces.len() as u8, pieces[0].clone());
        assert!(w.chunks[&(0, 0)].data.is_some());
    }

    #[test]
    fn the_ground_height_is_where_the_first_solid_block_from_the_top_ends() {
        let mut w = World::new(11);
        assert_eq!(w.standing_height(3, 4), None, "not loaded");
        w.chunks.insert((0, 0), Default::default());
        w.deliver_chunk(0, 0, land(11, 0, 0));
        assert_eq!(w.standing_height(3, 4), Some(30));
        w.deliver_chunk(1, 1, ChunkData::new());
        assert_eq!(w.standing_height(40, 40), None, "no such chunk");
    }
}
